fn redirected(metadata:&fs::Metadata)->bool {
    if metadata.file_type().is_symlink() {return true;}
    #[cfg(windows)] {use std::os::windows::fs::MetadataExt;return metadata.file_attributes()&0x400!=0;}
    #[cfg(not(windows))] false
}
pub(super) fn lease(path:&Path,directory:bool)->Result<fs::File,String> {
    let mut options=fs::OpenOptions::new();options.read(true);
    #[cfg(windows)] {
        use std::os::windows::fs::OpenOptionsExt;
        // Files deny writes/deletion. Directory leases deny deletion/redirection
        // but allow child-entry updates needed for the app's atomic publication.
        // OPEN_REPARSE_POINT checks the opened object, not a preceding path lookup.
        options.share_mode(if directory {3}else{1}).custom_flags(0x00200000|if directory {0x02000000}else{0});
    }
    let file=options.open(path).map_err(|e|format!("Cannot lease immutable finishing input {}: {e}",path.display()))?;
    let metadata=file.metadata().map_err(|e|e.to_string())?;
    if redirected(&metadata) || if directory {!metadata.is_dir()}else{!metadata.is_file()} {
        return Err("Finishing cache refuses reparse points or unexpected file types".into());
    }
    Ok(file)
}
pub(super) struct OwnedRoot {pub path:PathBuf,_leases:Vec<fs::File>}
impl OwnedRoot {
    pub fn open(path:&Path)->Result<Self,String> {
        if !path.is_absolute(){return Err("Finishing cache root must be absolute".into());}
        let mut guards=Vec::new();
        for parent in path.ancestors().collect::<Vec<_>>().into_iter().rev() {
            guards.push(lease(parent,true)?);
        }
        let canonical=path.canonicalize().map_err(|e|e.to_string())?;
        Ok(Self{path:canonical,_leases:guards})
    }
    /// Only fixed names or lowercase digest names are generated by the adapter.
    pub fn child(&self,name:&str)->Result<PathBuf,String> {
        if name.is_empty() || name.len()>128 || !name.bytes().all(|c|c.is_ascii_lowercase()
            || c.is_ascii_digit() || c==b'-' || c==b'.') || name=="." || name==".." {
            return Err("Invalid owned finishing artifact name".into());
        }
        let path=self.path.join(name);
        if let Ok(metadata)=fs::symlink_metadata(&path) {
            if redirected(&metadata){return Err("Finishing cache descendant is redirected".into());}
        }
        Ok(path)
    }
    pub fn subfolder(&self,name:&str)->Result<Self,String> {
        Self::open(&self.child(name)?)
    }
}
pub(super) fn finishing_root(folder:&Path)->Result<OwnedRoot,String> {
    let parent=OwnedRoot::open(folder)?;let path=parent.child("subject-finishing")?;
    if !path.exists(){fs::create_dir(&path).map_err(|e|e.to_string())?;}
    OwnedRoot::open(&path)
}
