/// Move an uncommitted owned stage. A directory move is NOT a receipt or commit:
/// reopen/lease and verify every payload after this move, then publish its marker.
/// Windows refuses directory moves while descendants deny delete sharing.
pub(super) fn move_stage(root:&OwnedRoot,stage:&str,destination:&str,id:&str)->Result<(),String> {
    let source=root.child(stage)?;let target=root.child(destination)?;
    if !stage.ends_with(".partial") || !source.is_dir() || target.exists() {
        return Err("Finishing staging requires a new owned directory and will not replace an existing artifact".into());
    }
    let state=jobs().lock().map_err(|e|e.to_string())?;
    if state.get(id).is_none_or(|job|job.cancelled||job.worker_error.is_some()) {
        return Err("Cancelled before finishing artifact staging".into());
    }
    #[cfg(windows)] {
        use std::os::windows::ffi::OsStrExt;
        use windows_sys::Win32::Storage::FileSystem::MoveFileExW;
        let from:Vec<u16>=source.as_os_str().encode_wide().chain(Some(0)).collect();
        let to:Vec<u16>=target.as_os_str().encode_wide().chain(Some(0)).collect();
        // Same-volume directory rename; no REPLACE_EXISTING flag.
        if unsafe {MoveFileExW(from.as_ptr(),to.as_ptr(),8)}==0 {
            return Err(format!("Cannot move owned finishing stage without overwrite: {}",std::io::Error::last_os_error()));
        }
    }
    #[cfg(not(windows))] return Err("Finishing atomic directory publication is not qualified on this platform".into());
    Ok(())
}
/// Commit marker is published last while verified picture/mask handles remain
/// held. The tiny marker is reopened and checked before returning a usable lease.
/// Cancellation recorded before the mutex wins; no replacement is ever allowed.
pub(super) fn commit_marker(root:&OwnedRoot,receipt:&Value,id:&str)->Result<fs::File,String> {
    let bytes=serde_json::to_vec(receipt).map_err(|e|e.to_string())?;
    if bytes.len()>128*1024 || receipt["complete"]!=true {
        return Err("Finishing commit requires one bounded complete receipt".into());
    }
    let pending=root.child("manifest.pending")?;let target=root.child("manifest.json")?;
    let mut file=fs::OpenOptions::new().write(true).create_new(true).open(&pending).map_err(|e|e.to_string())?;
    file.write_all(&bytes).and_then(|_|file.sync_all()).map_err(|e|e.to_string())?;drop(file);
    let mut state=jobs().lock().map_err(|e|e.to_string())?;
    if state.get(id).is_none_or(|job|job.cancelled||job.worker_error.is_some()) {
        return Err("Cancelled before finishing receipt commit".into());
    }
    #[cfg(windows)] {
        use std::os::windows::ffi::OsStrExt;
        use windows_sys::Win32::Storage::FileSystem::MoveFileExW;
        let from:Vec<u16>=pending.as_os_str().encode_wide().chain(Some(0)).collect();
        let to:Vec<u16>=target.as_os_str().encode_wide().chain(Some(0)).collect();
        if unsafe {MoveFileExW(from.as_ptr(),to.as_ptr(),8)}==0 {
            return Err(format!("Cannot commit finishing receipt without overwrite: {}",std::io::Error::last_os_error()));
        }
    }
    #[cfg(not(windows))] return Err("Finishing marker publication is not qualified on this platform".into());
    let mut held=lease(&target,false)?;
    if bounded_json(&mut held)?!=*receipt {return Err("Finishing commit marker changed during publication".into());}
    if let Some(job)=state.get_mut(id){job.logs.push(format!("Finishing receipt committed without overwrite: {}",target.display()));}
    Ok(held)
}
pub(super) fn verified_masks(folder:&Path,selection:&Selection,p:&Project,id:Option<&str>)->Result<VerifiedMasks,String> {
    let result=verified_mask_payload(folder,selection,p,id,"manifest.json")?;
    if result.receipt["appCommitted"]!=true||result.receipt["runtimeProfile"]!="manual-video-cpu-v1"
        ||result.receipt["runtimeSeal"]!=super::runtime::seal_identity() {
        return Err("Subject masks lack this application's current committed runtime provenance".into());
    }
    Ok(result)
}
/// Worker success is not app publication. Verify before moving, then compare
/// the pre-move identities under final-path leases before committing metadata.
/// Existing/incomplete destinations are preserved; this never repairs in place.
pub(super) fn publish_mask_stage(root:&OwnedRoot,stage:&str,destination:&str,
    selection:&Selection,p:&Project,id:&str)->Result<VerifiedMasks,String> {
    let source=root.child(stage)?;
    let generated=verified_mask_payload(&source,selection,p,Some(id),"manifest.json")?;
    let mut receipt=generated.receipt.clone();
    let mut mask=lease(&generated.path,false)?;let mask_expected=hashes(&mut mask,Some(id))?;
    let mut metadata=lease(&source.join("manifest.json"),false)?;
    let metadata_expected=hashes(&mut metadata,Some(id))?;
    drop(metadata);drop(mask);drop(generated);
    // Preserve the original worker evidence under a distinct fixed name. On
    // Windows rename refuses an existing target; no overwrite is permitted.
    fs::rename(source.join("manifest.json"),source.join("worker-manifest.json"))
        .map_err(|e|format!("Cannot preserve generated mask evidence: {e}"))?;
    move_stage(root,stage,destination,id)?;
    let target=root.subfolder(destination)?;
    let mask=lease_matching(&target.child("masks.pgmask")?,&mask_expected,Some(id))?;
    let metadata=lease_matching(&target.child("worker-manifest.json")?,&metadata_expected,Some(id))?;
    let payload=verified_mask_payload(&target.path,selection,p,Some(id),"worker-manifest.json")?;
    receipt["appCommitted"]=json!(true);
    receipt["runtimeProfile"]=json!("manual-video-cpu-v1");
    receipt["runtimeSeal"]=json!(super::runtime::seal_identity());
    // Integrity/provenance is not visual approval. A separate exact-artifact
    // review is required before this may become an export-ready feature.
    receipt["subjectQualityAccepted"]=json!(false);
    let marker=commit_marker(&target,&receipt,id)?;
    let result=verified_masks(&target.path,selection,p,Some(id))?;
    drop(marker);drop(payload);drop(metadata);drop(mask);
    Ok(result)
}
/// Generated worker metadata is evidence, never the final app commit marker.
pub(super) fn verified_mask_payload(folder:&Path,selection:&Selection,p:&Project,id:Option<&str>,marker:&str)->Result<VerifiedMasks,String> {
    if !matches!(marker,"manifest.json"|"worker-manifest.json") {return Err("Invalid fixed mask metadata name".into());}
    let root=OwnedRoot::open(folder)?;
    let mut manifest=lease(&root.child(marker)?,false)?;
    let receipt=bounded_json(&mut manifest)?;
    let canonical=receipt["canonicalRecipe"].as_str().ok_or("Missing exact canonical mask recipe")?;
    let expected=mask_recipe(selection,p)?;
    if canonical.len()>64*1024 || serde_json::from_str::<Value>(canonical).map_err(|e|e.to_string())?!=expected
        || receipt["maskIdentity"]!=hex::encode(Sha256::digest(canonical.as_bytes()))
        || receipt["schema"]!=1 || receipt["complete"]!=true || receipt["engine"]!=MASK_ENGINE
        || receipt["baseChecksum"]!=selection.base_identity || receipt["width"]!=p.width || receipt["height"]!=p.height
        || receipt["fps"]!=p.fps || receipt["frames"]!=selection.frame_count || receipt["profile"]!="limited-sdr709-yuv420p8"
        || receipt["generationProfile"]!=generation()
        || serde_json::from_value::<Selection>(receipt["selection"].clone()).map_err(|e|e.to_string())?.recipe()!=selection.recipe() {
        return Err("Subject masks are stale or unverified for this base, selection and generation profile".into());
    }
    let scale=(1024.0/(p.width.max(p.height) as f64)).min(1.0);
    // Python round uses ties-to-even; dimensions are positive and tightly bounded.
    let round=|value:f64| {let floor=value.floor();if value-floor==0.5 {if floor as u32%2==0 {floor}else{floor+1.0}}else{value.round()}};
    let w=round(p.width as f64*scale).max(1.0) as u32;let h=round(p.height as f64*scale).max(1.0) as u32;
    let mask=&receipt["mask"];let path=root.child("masks.pgmask")?;let mut file=lease(&path,false)?;
    if file.metadata().map_err(|e|e.to_string())?.len()>MASK_MAX_BYTES {return Err("Subject masks exceed the 2 GiB cache bound".into());}
    let (bytes,md5,sha)=hashes(&mut file,id)?;
    if bytes>MASK_MAX_BYTES || mask["schema"]!=1 || mask["format"]!="PGMSK001" || mask["width"]!=w
        || mask["height"]!=h || mask["frames"]!=selection.frame_count || mask["bytes"]!=bytes
        || mask["checksum"]!=md5 || mask["sha256"]!=sha {
        return Err("Subject mask content does not match its bounded checksum receipt".into());
    }
    mask_schedule(&mut file,w,h,selection.frame_count,id)?;
    Ok(VerifiedMasks{path,identity:receipt["maskIdentity"].as_str().unwrap().into(),sha256:sha,
        receipt,_root:root,_leases:vec![manifest,file]})
}

pub(super) fn validate_profile(info:&Value,p:&Project,count:u32)->Result<(),String> {
    let streams=info["streams"].as_array().ok_or("Missing finishing base streams")?;
    let videos:Vec<_>=streams.iter().filter(|s|s["codec_type"]=="video").collect();
    if videos.len()!=1 || count==0 || count>1_800_000 || p.width==0 || p.height==0
        || p.width>4096 || p.height>4096 || !(1..=60).contains(&p.fps) {
        return Err("Subject finishing requires one bounded normalized video stream".into());
    }
    let v=videos[0];let rate=format!("{}/1",p.fps);
    if v["width"]!=p.width || v["height"]!=p.height || v["nb_frames"]!=count.to_string()
        || v["r_frame_rate"]!=rate || v["avg_frame_rate"]!=rate {
        return Err("Subject selection no longer matches this exact base geometry/frame schedule. Prepare the base and select the subject again.".into());
    }
    for (field,expected) in [("codec_name","h264"),("pix_fmt","yuv420p"),("color_range","tv"),
        ("color_space","bt709"),("color_primaries","bt709"),("color_transfer","bt709"),
        ("sample_aspect_ratio","1:1"),("field_order","progressive")] {
        if v[field]!=expected {return Err(format!("Subject finishing requires explicitly declared limited SDR BT.709, square-pixel progressive bases ({field}={}). Unknown/Log/HDR colour is not silently reinterpreted.",v[field]));}
    }
    if v["tags"].as_object().is_some_and(|tags|tags.keys().any(|key|key.eq_ignore_ascii_case("rotate")))
        || v["side_data_list"].as_array().is_some_and(|data|!data.is_empty()) {
        return Err("Subject finishing requires a physically normalized base with no rotation/display metadata".into());
    }
    Ok(())
}

