/// New finishing artifacts use opened-object protection on the ACTUAL lock,
/// not the legacy derived lock-file helper. A sharing violation waits without
/// reserving scarce model/GPU resources; cancellation and pause remain live.
pub(super) fn lock_owned(root:&OwnedRoot,name:&str,id:&str)->Result<fs::File,String> {
    let path=root.child(&format!("{name}.lock"))?;
    #[cfg(windows)] {
        use std::os::windows::fs::{OpenOptionsExt,MetadataExt};
        loop {
            checkpoint(id)?;
            match fs::OpenOptions::new().read(true).write(true).create(true).share_mode(1).custom_flags(0x00200000).open(&path) {
                Ok(file)=> {
                    let info=file.metadata().map_err(|e|e.to_string())?;
                    if !info.is_file()||info.file_attributes()&0x400!=0 {return Err("Finishing artifact lock is redirected or has an unexpected type".into());}
                    return Ok(file);
                }
                Err(error) if matches!(error.raw_os_error(),Some(32|33))=>thread::sleep(Duration::from_millis(100)),
                Err(error)=>return Err(format!("Cannot open owned finishing lock: {error}")),
            }
        }
    }
    #[cfg(not(windows))] {let _=(path,id);Err("Owned finishing locks are not qualified on this platform".into())}
}
/// Cooperate with the legacy byte-range lock, while checking the actual opened
/// lock object before touching it. The surrounding format-root lease protects
/// its ancestors; OPEN_REPARSE_POINT avoids following a redirected lock.
pub(super) fn lock_legacy_fragment(path:&Path,id:&str)->Result<fs::File,String> {
    #[cfg(windows)] {
        use std::os::windows::fs::OpenOptionsExt;
        let file=fs::OpenOptions::new().read(true).write(true).create(true).truncate(false)
            .share_mode(3).custom_flags(0x00200000).open(path.with_extension("lock")).map_err(|e|e.to_string())?;
        let metadata=file.metadata().map_err(|e|e.to_string())?;
        if !metadata.is_file()||redirected(&metadata){return Err("Legacy adoption lock is redirected or has an unexpected type".into());}
        loop {
            checkpoint(id)?;
            match fs2::FileExt::try_lock_exclusive(&file) {
                Ok(())=>return Ok(file),
                Err(error) if error.raw_os_error()==fs2::lock_contended_error().raw_os_error()=>thread::sleep(Duration::from_millis(100)),
                Err(error)=>return Err(format!("Legacy adoption lock failed: {error}")),
            }
        }
    }
    #[cfg(not(windows))] {let _=(path,id);Err("Legacy adoption locks are not qualified on this platform".into())}
}
pub(super) fn hashes(file:&mut fs::File,id:Option<&str>)->Result<(u64,String,String),String> {
    file.seek(SeekFrom::Start(0)).map_err(|e|e.to_string())?;
    let mut md5=Md5::new();let mut sha=Sha256::new();let mut bytes=0u64;let mut chunk=[0u8;256*1024];
    loop {
        if let Some(id)=id {if verification_cancelled(id) {return Err("Cancelled during finishing verification".into());}}
        let count=file.read(&mut chunk).map_err(|e|e.to_string())?;if count==0 {break;}
        bytes+=count as u64;md5.update(&chunk[..count]);sha.update(&chunk[..count]);
    }
    file.seek(SeekFrom::Start(0)).map_err(|e|e.to_string())?;
    Ok((bytes,hex::encode(md5.finalize()),hex::encode(sha.finalize())))
}
pub(super) fn lease_matching(path:&Path,expected:&(u64,String,String),id:Option<&str>)->Result<fs::File,String> {
    let mut file=lease(path,false)?;
    if hashes(&mut file,id)?!=*expected {
        return Err("Finishing picture changed during staging; no completion receipt was published".into());
    }
    Ok(file)
}
fn verification_cancelled(id:&str)->bool {
    jobs().lock().map(|jobs|jobs.get(id).is_none_or(|job|job.cancelled||job.worker_error.is_some())).unwrap_or(true)
}
pub(super) fn bounded_json(file:&mut fs::File)->Result<Value,String> {
    let mut bytes=Vec::new();file.take(128*1024+1).read_to_end(&mut bytes).map_err(|e|e.to_string())?;
    if bytes.len()>128*1024 {return Err("Finishing receipt exceeds its bounded metadata budget".into());}
    serde_json::from_slice(&bytes).map_err(|e|format!("Invalid finishing receipt: {e}"))
}
fn word(file:&mut fs::File)->Result<u32,String> {
    let mut bytes=[0u8;4];file.read_exact(&mut bytes).map_err(|_|"Truncated mask cache")?;Ok(u32::from_le_bytes(bytes))
}
fn mask_schedule(file:&mut fs::File,w:u32,h:u32,count:u32,id:Option<&str>)->Result<(),String> {
    let mut magic=[0u8;8];file.read_exact(&mut magic).map_err(|_|"Truncated mask header")?;
    if magic!=*b"PGMSK001" || word(file)?!=w || word(file)?!=h || word(file)?!=count {
        return Err("Subject mask header does not match its exact receipt".into());
    }
    let pixels=w as u64*h as u64;
    for _ in 0..count {
        if let Some(id)=id {if verification_cancelled(id){return Err("Cancelled while verifying subject masks".into());}}
        let payload=word(file)?;
        if payload==0 || payload%5!=0 || payload as u64>pixels*5 {return Err("Invalid bounded mask RLE payload".into());}
        let mut expanded=0u64;
        for _ in 0..payload/5 {
            let run=word(file)?;let mut alpha=[0u8;1];file.read_exact(&mut alpha).map_err(|_|"Truncated mask run")?;
            expanded+=run as u64;
            if run==0 || expanded>pixels{return Err("Subject mask RLE overflow or empty run".into());}
        }
        if expanded!=pixels {return Err("Subject mask RLE does not cover the complete frame".into());}
    }
    let mut tail=[0u8;1];if file.read(&mut tail).map_err(|e|e.to_string())?!=0 {
        return Err("Unexpected trailing subject mask data".into());
    }
    Ok(())
}
