import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import ts from "typescript";
const source = await readFile(new URL("../src/utils/eventNaming.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ES2020 } }).outputText;
const { emptyEvent, eventTitle, eventPeriod, draftForDay, weekendPaths } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`);
const draft = { ...emptyEvent(), eventGroup: "Mounted Games Victoria", eventType: "Teams", venue: "Ayr Hill" };
assert.equal(eventTitle(draft, ["2026-10-24", "2026-10-25"]), "Mounted Games Victoria - Teams - Ayr Hill - October 2026");
assert.equal(eventPeriod(["2026-10-31", "2026-11-01"]), "October & November 2026");
assert.equal(eventPeriod(["2026-12-31", "2027-01-01"]), "December 2026 & January 2027");
assert.equal(eventPeriod(["2026-10-24", "2026-12-05"]), "October & December 2026");
assert.equal(eventTitle({ ...draft, customName: "Monbulk Pony Club Rally" }, ["2026-10-04"]), "Monbulk Pony Club Rally");
const legacy = { hasCustomName: true, name: "24 - Polocrosse - Spring Carnival - Sale - October 2026", path: "x", dateKey: "2026-10-24" };
assert.equal(draftForDay(legacy).customName, "Polocrosse - Spring Carnival - Sale - October 2026");
const dstDays = [{ path: "sat", dateKey: "2026-10-03" }, { path: "sun", dateKey: "2026-10-04" }, { path: "mon", dateKey: "2026-10-05" }];
assert.deepEqual(weekendPaths(dstDays[0], dstDays), ["sat", "sun"]);
assert.deepEqual(weekendPaths(dstDays[1], dstDays), ["sat", "sun"]);
assert.deepEqual(weekendPaths(dstDays[2], dstDays), ["mon"]);
console.log("PASS: event names, month and year boundaries, non-consecutive months, legacy wording and daylight-saving weekend selection.");
