"""Build-time inventory, never a self-authorizing runtime hash generator.

Checks imported payloads against the pinned source archives/wheels before
recording a development seal. Installer-generated journals and unused CLI
wrappers remain build-tool outputs, not publisher-signed executable claims.
Release qualification, licences and representative footage are separate gates.
"""
import argparse
import configparser
import hashlib
import json
from pathlib import Path, PurePosixPath
import stat
import zipfile

REPO = Path(__file__).resolve().parent.parent
SCRIPTS = ("subject_mask_worker.py", "subject_mask_job.py", "subject_masks_contract.py",
           "subject_mask_cache.py", "subject_media_contract.py", "subject_process.py")
SAM = "sam2-2b90b9f5ceec907a1c18123530e92e794ad901a4.zip"
SAM_HASH = "fe93082a71a885a427894b1eab76341768781b6b58a298a0717e03862097d137"
PYTHON_HASH = "97dae5274cc54867065e8d5a3226e48c35017ed332a0fdb0e27d5b5821961297"
MODEL_HASH = "7402e0d864fa82708a20fbd15bc84245c2f26dff0eb43a4b5b93452deb34be69"


def file_hash(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def safe_name(name):
    path = PurePosixPath(name)
    if not name or path.is_absolute() or "\\" in name or ":" in name or any(
            part in ("", ".", "..") or part.endswith((".", " ")) for part in name.split("/")):
        raise ValueError(f"Unsafe archive/seal path: {name}")
    return name


def tree_files(folder):
    result = {}
    seen = set()
    for path in folder.rglob("*"):
        info = path.lstat()
        if path.is_symlink() or getattr(info, "st_file_attributes", 0) & 0x400:
            raise ValueError("Candidate contains a redirected descendant")
        if path.is_file():
            relative = safe_name(path.relative_to(folder).as_posix())
            if path.suffix.lower() == ".pyc":
                raise ValueError("Generated bytecode is not admitted; preserve it outside the import trees")
            if relative.lower() in seen:
                raise ValueError("Candidate contains case-colliding names")
            seen.add(relative.lower())
            result[relative] = path
        elif not path.is_dir():
            raise ValueError("Unexpected candidate file type")
    return result


def archive_file(archive, entry, literal_symlink=False):
    if stat.S_ISLNK(entry.external_attr >> 16) and not literal_symlink:
        raise ValueError("Input archive contains a symlink")
    with archive.open(entry) as stream:
        return entry.file_size, hashlib.file_digest(stream, "sha256").hexdigest()


def qualify(root, runner):
    spec = json.loads((REPO / "scripts/subject-finishing/runtime/wheels-manual-cpu.json").read_text())
    if spec["profile"] != "manual-video-cpu-v1" or len(spec["wheels"]) != 21:
        raise ValueError("Expected the exact development manual CPU profile")
    expected = {}
    generated = {"runtime/resolved-manual-packages.json"}
    origins = {}
    seen = set()

    def add(name, identity, origin):
        safe_name(name)
        if name.lower() in seen:
            raise ValueError(f"Colliding pinned payload: {name}")
        seen.add(name.lower())
        expected[name] = identity
        origins[name] = origin

    python_zip = REPO / ".build-cache/subject-finishing-evaluation-cpu/python-3.13.16-embed-amd64.zip"
    if file_hash(python_zip) != PYTHON_HASH:
        raise ValueError("Embedded Python source archive changed")
    with zipfile.ZipFile(python_zip) as archive:
        for entry in archive.infolist():
            if entry.is_dir() or entry.filename == "python313._pth":
                continue
            add("runtime/" + entry.filename, archive_file(archive, entry), "python-embed")
    pth = REPO / "scripts/subject-finishing/runtime/python313-manual._pth"
    add("runtime/python313._pth", (pth.stat().st_size, file_hash(pth)), "app-no-site-policy")

    for wheel in spec["wheels"]:
        wheel_path = root / "wheelhouse" / safe_name(wheel["file"])
        if file_hash(wheel_path) != wheel["sha256"]:
            raise ValueError("Pinned offline wheel changed")
        with zipfile.ZipFile(wheel_path) as archive:
            top_dist_info = set()
            for entry in archive.infolist():
                if entry.is_dir():
                    continue
                name = safe_name(entry.filename)
                if ".data/" in name:
                    _, tail = name.split(".data/", 1)
                    kind, tail = tail.split("/", 1)
                    if kind == "scripts":
                        generated.add("runtime/Lib/site-packages/bin/" + safe_name(tail))
                        continue
                    if kind not in ("purelib", "platlib", "data"):
                        raise ValueError("Unsupported wheel installation scheme")
                    name = tail
                parts = name.split("/")
                if len(parts) == 2 and parts[0].endswith(".dist-info"):
                    top_dist_info.add(parts[0])
                    if parts[1] == "RECORD":
                        generated.add("runtime/Lib/site-packages/" + name)
                        continue
                    if parts[1] == "entry_points.txt":
                        parser = configparser.ConfigParser(interpolation=None)
                        parser.read_string(archive.read(entry).decode("utf-8"))
                        if parser.has_section("console_scripts"):
                            for command in parser["console_scripts"]:
                                generated.add("runtime/Lib/site-packages/bin/" + safe_name(command) + ".exe")
                add("runtime/Lib/site-packages/" + name, archive_file(archive, entry), "wheel:" + wheel["sha256"])
            for folder in top_dist_info:
                for name in ("INSTALLER", "REQUESTED"):
                    generated.add("runtime/Lib/site-packages/" + folder + "/" + name)

    sam = root / SAM
    if file_hash(sam) != SAM_HASH:
        raise ValueError("SAM source archive changed")
    add(SAM, (sam.stat().st_size, SAM_HASH), "sam-source-archive")
    with zipfile.ZipFile(sam) as archive:
        prefix = SAM[:-4] + "/"
        for entry in archive.infolist():
            if not entry.filename.startswith(prefix):
                raise ValueError("Unexpected SAM source root")
            name = entry.filename[len(prefix):]
            if (name.startswith("sam2/") and name.endswith((".py", ".yaml"))) or name in ("LICENSE", "LICENSE_cctorch"):
                # The reviewed Windows provisioner extracts alias entries as
                # regular literal bytes; it never creates/follows source links.
                add("vendor/" + name, archive_file(archive, entry, literal_symlink=True), "sam-source")
    model = root / "models/sam2.1_hiera_tiny.pt"
    add("models/sam2.1_hiera_tiny.pt", (156008466, MODEL_HASH), "sam-weights")
    for name in SCRIPTS:
        source = REPO / "src-tauri/scripts" / name
        add("runner/" + name, (source.stat().st_size, file_hash(source)), "app-source")
    worker = runner.parent / "photogogo-subject-finishing.exe"
    add("worker/photogogo-subject-finishing.exe", (worker.stat().st_size, file_hash(worker)), "trusted-application-build-output")

    actual = {SAM: sam}
    for tree in ("runtime", "vendor", "models"):
        actual.update({tree + "/" + name: path for name, path in tree_files(root / tree).items()})
    actual.update({"runner/" + name: path for name, path in tree_files(runner).items()})
    actual["worker/photogogo-subject-finishing.exe"] = worker
    if set(actual) != set(expected) | generated:
        missing = sorted((set(expected) | generated) - set(actual))
        extra = sorted(set(actual) - set(expected) - generated)
        raise ValueError(f"Candidate inventory differs: missing={missing[:8]}, extra={extra[:8]}")
    expected_dirs = set()
    for name in actual:
        parts = name.split("/")
        expected_dirs.update("/".join(parts[:index]) for index in range(1, len(parts)))
    actual_dirs = {"worker"}  # One fixed app-owned binary, not an import directory.
    for name, folder in [(tree, root / tree) for tree in ("runtime", "vendor", "models")] + [("runner", runner)]:
        actual_dirs.add(name)
        actual_dirs.update(name + "/" + path.relative_to(folder).as_posix()
                           for path in folder.rglob("*") if path.is_dir())
    if actual_dirs != expected_dirs:
        raise ValueError(f"Unexpected or missing directory shape: {sorted(actual_dirs ^ expected_dirs)[:8]}")
    files = []
    for name, path in sorted(actual.items()):
        identity = (path.stat().st_size, file_hash(path))
        if name in expected and identity != expected[name]:
            raise ValueError(f"Installed payload differs from its trusted input: {name}")
        if name.endswith("/INSTALLER") and name in generated and path.read_bytes() != b"pip\n":
            raise ValueError("Unexpected installer marker")
        if name.endswith("/REQUESTED") and name in generated and identity[0] != 0:
            raise ValueError("Unexpected requested-package marker")
        files.append({"path": name, "bytes": identity[0], "sha256": identity[1],
                      "origin": origins.get(name, "trusted-build-tool-output")})
    return {"schema": 1, "profile": "manual-video-cpu-v1", "noSite": True,
            "qualificationCandidate": True, "files": files}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--runner", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    manifest = qualify(args.root.resolve(), args.runner.resolve())
    payload = json.dumps(manifest, separators=(",", ":"), ensure_ascii=True).encode("utf-8")
    if len(payload) > 8 * 1024 * 1024 or len(manifest["files"]) > 40000:
        raise ValueError("Development runtime seal exceeds bounded inventory")
    # Exclusive artifact generation; an old qualification record is preserved.
    with args.output.open("xb") as stream:
        stream.write(payload)
    print(json.dumps({"files": len(manifest["files"]), "manifestBytes": len(payload),
                      "sha256": hashlib.sha256(payload).hexdigest(), "qualificationCandidate": True}))


if __name__ == "__main__":
    main()
