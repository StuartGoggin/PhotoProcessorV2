import { chromium } from "playwright";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";

await mkdir("qa", { recursive: true });
const browser = await chromium.launch({ channel: "msedge", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const failures = [];
  page.on("pageerror", (error) => failures.push(error.message));
  await page.goto("http://127.0.0.1:1431/studio-preview.html");
  await page.getByRole("heading", { name: "Choose once. Use for every clip." }).waitFor();
  await page.locator("main").evaluate((node) => node.scrollTo(0, 0));
  await page.screenshot({ path: "qa/video-studio-desktop.png", fullPage: true });
  await page.getByRole("button", { name: /Render clip ·/ }).click();
  await page.waitForFunction(() => window.__lastStudioRequest?.renderKind === "clip");
  let request = await page.evaluate(() => window.__lastStudioRequest);
  assert.equal(request.assembleOnly, false, "individual render is independent of assembly preference");
  assert.equal(request.project.width, 3840); assert.equal(request.project.fps, 50); assert.equal(request.project.bitrateMbps, 32);
  await page.getByLabel("Clip title (blank = hidden)").fill("Edited warm-up");
  assert.equal(await page.getByRole("button", { name: /Render clip ·/ }).isDisabled(), true);
  await page.getByText("Previous render · outdated", { exact: false }).waitFor();
  await page.getByLabel("I reviewed this clip, titles and replay ranges").check();
  await page.getByLabel("Resolution", { exact: true }).selectOption("1920");
  await page.getByLabel("Frame rate", { exact: true }).selectOption("30");
  await page.getByLabel("Video bitrate · Mbps").fill("18");
  await page.getByRole("button", { name: /Render clip ·/ }).click();
  await page.waitForFunction(() => window.__lastStudioRequest?.project.bitrateMbps === 18);
  request = await page.evaluate(() => window.__lastStudioRequest);
  assert.equal(request.project.width, 1920); assert.equal(request.project.height, 1080); assert.equal(request.project.fps, 30);
  assert.equal(request.project.clips[0].revision, 1);
  await page.getByRole("button", { name: /Final run/ }).click();
  await page.getByLabel("I reviewed this clip, titles and replay ranges").check();
  await page.getByRole("button", { name: "Render & assemble complete video" }).click();
  await page.waitForFunction(() => window.__lastStudioRequest?.renderKind === "project");
  await page.screenshot({ path: "qa/video-studio-prepared.png", fullPage: true });
  await page.locator("summary").filter({ hasText: /background music/i }).click();
  await page.getByText("Creative brief", { exact: false }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: "qa/video-studio-music.png" });
  await page.getByText("Detailed job log", { exact: true }).click();
  await page.getByText(/Fixture detailed event log/).waitFor();
  await page.getByText(/Status check overdue/).waitFor();
  await page.getByRole("button", { name: "Open log folder" }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: "qa/video-studio-job-diagnostics.png" });
  await page.setViewportSize({ width: 900, height: 900 });
  await page.locator("main").evaluate((node) => node.scrollTo(0, 0));
  await page.screenshot({ path: "qa/video-studio-narrow.png", fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, "no horizontal overflow at the app's minimum width");
  assert.deepEqual(failures, []);
  await page.evaluate(() => { window.__confirmResult = false; });
  await page.getByRole("button", { name: "Clear all Studio renders", exact: true }).click();
  assert.equal(await page.evaluate(() => !!window.__studioCleared), false);
  await page.evaluate(() => { window.__confirmResult = true; });
  await page.getByRole("button", { name: "Clear all Studio renders", exact: true }).click();
  await page.getByText("Cleared 1 Studio jobs. Ready to render from scratch.").waitFor();
  await page.getByText("No renders queued yet.").waitFor();
  const cleared = await page.evaluate(() => JSON.parse(localStorage.getItem("photogogo.videoStudio.project.v1")));
  assert.ok(cleared.clips.every((clip) => !clip.rendered));
  assert.equal(cleared.clips.length, 3);
  console.log("PASS: render dispatch, edit invalidation, resolution/FPS/bitrate propagation, final assembly and responsive layout.");
} finally { await browser.close(); }
