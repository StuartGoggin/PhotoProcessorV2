// Public native controller tracer: a fixed cached sample, no runtime promotion.
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {createHash} from 'node:crypto';
import {mkdtemp, readFile, readdir,lstat} from 'node:fs/promises';
import {resolve, join, dirname, relative, isAbsolute} from 'node:path';

const root=resolve('.');
const binary=resolve(process.argv[2]??'test-output/subject-picture-handoff-v4/bin/PhotoGoGo-Cached-Picture-Test.exe');
const backend=process.argv[3]??'cpu';
assert.ok(process.argv.length<=4&&['cpu','default-gpu'].includes(backend));
assert.ok(!isAbsolute(relative(root,binary))&&!relative(root,binary).startsWith('..'));
const buildRoot=dirname(dirname(binary));
const receipt=JSON.parse(await readFile(join(buildRoot,'build-receipt.json')));
assert.equal(receipt.kind,'native-cached-picture-handoff-build');
assert.equal(receipt.testFaultsEnabled,false);
const hash=async path=>createHash('sha256').update(await readFile(path)).digest('hex');
assert.equal(await hash(binary),receipt.executable.sha256);
assert.ok(receipt.sources.some(pin=>pin.path==='src-tauri/native/subject_finishing/shaders.h'));
for(const pin of receipt.sources)assert.equal(await hash(resolve(pin.path)),pin.sha256);
const folder=await mkdtemp(join(root,'test-output','subject-picture-public-'));
const output=join(folder,'private-user-and-media-path');
const child=spawn(binary,['--run-case',output,'--sample','black-horse','--backend',backend,'--confirm-idle'],
 {windowsHide:true,stdio:['ignore','pipe','pipe']});
let out='',err='',timedOut=false;
const timer=setTimeout(()=>{timedOut=true;child.kill();},200000);
child.stdout.on('data',data=>{out+=data;assert.ok(Buffer.byteLength(out)<65536);});
child.stderr.on('data',data=>{err+=data;assert.ok(Buffer.byteLength(err)<65536);});
const code=await new Promise((done,reject)=>{child.once('error',reject);child.once('close',done);}).finally(()=>clearTimeout(timer));
assert.equal(timedOut,false);assert.equal(code,0,err);assert.equal(err,'');
const reportText=await readFile(join(output,'picture-report.json'),'utf8');
const report=JSON.parse(reportText);
assert.equal(report.kind,'photogogo-cached-picture-benchmark');
assert.equal(report.schema,1);assert.equal(report.sample,'black-horse');assert.equal(report.backend,backend);
if(backend==='cpu')assert.equal(report.actualVendorId,0);else assert.ok(report.actualVendorId>0);
assert.equal(report.decodedVideoFrames,100);
assert.equal(report.videoPackets,100);assert.equal(report.audioPacketsCopiedExactly,95);
assert.equal(report.cpuPictureParallelism,backend==='cpu'?4:0);assert.equal(report.outputFile,`black-horse-${backend}.mp4`);
assert.equal(report.ownedActiveProcesses,0);assert.ok(report.ownedPeakBytes>0&&report.ownedPeakBytes<=4*1024**3);
assert.ok(report.wallSeconds>0&&report.wallSeconds<180);
assert.equal(report.outputSha256,await hash(join(output,report.outputFile)));
assert.equal(report.cudaInferenceReady,false);assert.equal(report.subjectQualityAccepted,false);
assert.equal(report.productionExportQualified,false);assert.equal(report.inferenceRuntimeBundled,false);
assert.equal(report.pixelParityChecked,false);assert.equal(report.continuousPlaybackReviewed,false);
assert.deepEqual(report.hostChanges,{dependenciesInstalled:false,driverChanged:false,executionPolicyChanged:false});
assert.equal(report.completionProtocol,'zero-byte-report-sha256-marker-v1');
assert.equal(report.runnerSha256,receipt.executable.sha256);
const marker=`picture-report.${createHash('sha256').update(reportText).digest('hex')}.committed`;
const markerStat=await lstat(join(output,marker));assert.ok(markerStat.isFile()&&!markerStat.isSymbolicLink());assert.equal(markerStat.size,0);
assert.deepEqual((await readdir(output)).sort(),[`black-horse-${backend}.mp4`,'picture-report.json',marker].sort());
for(const text of [reportText,out,err])assert.ok(!text.includes('private-user-and-media-path')&&!text.includes(root));
for(const pin of receipt.sources)assert.equal(await hash(resolve(pin.path)),pin.sha256);
assert.equal(await hash(binary),receipt.executable.sha256);
console.log(JSON.stringify({event:'passed',seam:'native-fixed-cached-picture',backend,actualVendorId:report.actualVendorId,folder,productionExportQualified:false}));
