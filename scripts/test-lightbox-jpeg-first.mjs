import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
const cache=new Map();
function load(file){file=path.resolve(file);if(cache.has(file))return cache.get(file).exports;const module={exports:{}};cache.set(file,module);const code=ts.transpileModule(readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;new Function('require','module','exports',code)(name=>load(path.resolve(path.dirname(file),name+'.ts')),module,module.exports);return module.exports;}
const {lightboxCatalogue,photoForSource}=load('src/utils/lightboxCatalogue.ts');
const browse=load('src/utils/lightboxBrowse.ts');
const {defaultLightboxBrowse,projectLightboxCatalogue,photoReviewState}=browse;
const file=(name,size=100,extra={})=>({type:'file',name,path:name,size,sourceStamp:size+':1',...extra});
const facts={review:{entries:{}},selections:Object.fromEntries(Array.from({length:588},(_,i)=>['photo-'+String(i).padStart(4,'0')+'.jpg',{selected:true,favourite:false}]))};
const big=lightboxCatalogue(Array.from({length:888},(_,i)=>file('photo-'+String(i).padStart(4,'0')+'.jpg')));
const count=(base,quick,data=facts,extra={})=>projectLightboxCatalogue(base,{...defaultLightboxBrowse,quick,...extra},data,'').folders.get('').length;
assert.equal(count(big,'all'),888);
assert.equal(count(big,'selected'),588);
assert.equal(count(big,'needsReview'),300,'historical selections must remove 588 from Needs review');
assert.equal(count(big,'reviewed'),588);
const photo=big.photos.get('photo-0000.jpg');
const explicit=structuredClone(facts);explicit.review.entries['photo-0000.jpg']={sourceStamp:'100:1',reviewed:false};
assert.equal(photoReviewState(photo,explicit),'needsReview','manual false overrides old positive');
explicit.review.entries['photo-0000.jpg'].sourceStamp='changed';
assert.equal(photoReviewState(photo,explicit),'unknown','stale explicit records stop inference');
assert.equal(photoReviewState(photo,{...facts,review:null}),'unknown');
assert.equal(photoReviewState(photo,{...facts,selections:null}),'unknown');
const pair=lightboxCatalogue([file('raw.CR3',900,{cameraJpeg:'camera.jpg'}),file('camera.jpg',200),file('camera_improved.jpg',250)]);
const canonical=pair.photos.get('raw.CR3');
const pairFacts={review:{entries:{'camera.jpg':{reviewed:false,sourceStamp:'200:1'}}},selections:{'camera_improved.jpg':{selected:true,favourite:false}}};
assert.equal(photoReviewState(canonical,pairFacts),'needsReview','pre-pair explicit JPEG false survives');
pairFacts.review.entries={};assert.equal(photoReviewState(canonical,pairFacts),'reviewed');
pairFacts.review.entries['raw.cr3']={reviewed:false,sourceStamp:'900:1'};
assert.equal(photoReviewState(canonical,pairFacts),'needsReview');
assert.equal(canonical.node.path,'raw.CR3');
assert.equal(photoForSource(canonical,'cameraJpeg').bw,undefined);
assert.equal(browse.lightboxDisplayNode(canonical).name,'camera.jpg');
assert.equal(browse.lightboxDisplayNode(canonical).size,200);
const mixed=lightboxCatalogue([file('a.CR3',900,{captureMetadataPending:true}),file('a.jpg',200,{captureMetadataPending:true}),file('unmatched.CR3')]);
assert.equal(count(mixed,'all',{review:{entries:{}},selections:{}}),1,'pending RAW does not create duplicate navigation rows');
assert.equal(count(mixed,'all',null,{showUnpairedRaw:true}),3,'unpaired RAW disclosure remains accessible');
const rawOnly=lightboxCatalogue([file('alone.CR3'),file('alone_improved.jpg',10,{rawSource:'alone.CR3',rawKind:'improved'})]);
assert.equal(count(rawOnly,'all',null),1,'RAW-only originals stay visible despite derived JPEG');
assert.equal(count(pair,'all',null),1);
const sorted=lightboxCatalogue([file('a.CR3',900,{cameraJpeg:'z.jpg'}),file('z.jpg',10),file('b.CR3',100,{cameraJpeg:'a.jpg'}),file('a.jpg',800)]);
for(const sort of ['name','size'])assert.equal(projectLightboxCatalogue(sorted,{...defaultLightboxBrowse,sort},null,'').folders.get('')[0].node.path,sort==='name'?'b.CR3':'a.CR3','sort follows visible JPEG');
const duplicate=lightboxCatalogue([file('raw.CR3',900,{cameraJpeg:'camera.jpg'}),file('camera.jpg',200),file('camera{Out of Focus 1}.jpg',200)]);
const duplicateFacts={review:{entries:{}},selections:{'camera.jpg':{selected:true,favourite:false}}};
assert.equal(count(duplicate,'needsReview',duplicateFacts),duplicate.folders.get('').length,'ambiguous child flags never prove review');
const pendingFailure=projectLightboxCatalogue(mixed,defaultLightboxBrowse,null,'',node=>node.name==='unmatched.CR3');
assert.ok(pendingFailure.folders.get('').some(p=>p.node.name==='unmatched.CR3'),'failed targets stay pinned through RAW hiding');
console.log('JPEG-first review: historical 888/588, explicit records, stamps, RAW visibility, identity and visible sorting passed.');
