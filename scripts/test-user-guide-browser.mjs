import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { spawn } from 'node:child_process';
import { setTimeout as delay } from 'node:timers/promises';
const { chromium } = await import(process.env.PHOTOGOGO_PLAYWRIGHT_PATH ? pathToFileURL(process.env.PHOTOGOGO_PLAYWRIGHT_PATH).href : 'playwright');
const output = 'test-output/user-guide-integration';
await mkdir(output, {recursive: true});
const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--host', '127.0.0.1', '--port', '1466', '--strictPort'], {windowsHide: true, stdio: ['ignore', 'pipe', 'pipe']});
let logs = '', browser;
const checks = [], errors = [], external = [];
server.stdout.on('data', d => logs += d); server.stderr.on('data', d => logs += d);
try {
  for (let i=0;i<80;i++) { if (server.exitCode !== null) throw Error(logs); try {if ((await fetch('http://127.0.0.1:1466/help-preview.html')).ok) break;} catch {} await delay(250); }
  browser = await chromium.launch({channel: 'msedge', headless: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 1000}, reducedMotion: 'reduce'});
  page.setDefaultTimeout(12000);
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => {if(m.type()==='error')errors.push(m.text());});
  page.on('response', r=>{if(r.status()>=400)errors.push(r.status()+': '+r.url());});
  page.on('request', r => {if (/^https?:/.test(r.url()) && !r.url().startsWith('http://127.0.0.1:1466/')) external.push(r.url());});
  await page.goto('http://127.0.0.1:1466/help-preview.html');
  const button = name => page.getByRole('button', {name, exact: true});
  await page.getByRole('navigation', {name:'Main navigation'}).getByRole('button', {name:/Settings/}).click();
  const field = page.locator('#setting-staging_dir');
  if(process.argv.includes('--capture')){
    await field.waitFor();
    await page.evaluate(()=>{['source_root','staging_dir','archive_dir'].forEach((key,i)=>{const rect=document.querySelector('#setting-'+key).getBoundingClientRect(),mark=document.createElement('span');mark.dataset.guideMarker='true';mark.textContent=String(i+1);mark.style.cssText='position:fixed;z-index:10000;display:grid;place-items:center;width:29px;height:29px;border-radius:50%;background:#edc880;color:#132b39;border:2px solid white;font:bold 15px Segoe UI;box-shadow:0 3px 10px #0006;left:'+(rect.left-14)+'px;top:'+(rect.top-13)+'px';document.body.append(mark);});});
    await page.screenshot({path:'docs/user-guide/source/settings-screen.png'});
    await page.locator('[data-guide-marker]').evaluateAll(nodes=>nodes.forEach(n=>n.remove()));
  }
  await field.fill('D:/Unsaved work');
  await button('Help for this page').click({timeout: 4000});
  const dialog = page.getByRole('dialog', {name: 'PhotoGoGo User Guide'});
  await dialog.waitFor();
  const frame = page.frameLocator('iframe[title="PhotoGoGo User Guide"]');
  await frame.locator('#ch-02-title').waitFor();
  await page.getByText('Opening guide…', {exact: true}).waitFor({state: 'hidden'});
  checks.push('Contextual Help opens Settings chapter without navigating');
  const sandbox = await page.locator('iframe').getAttribute('sandbox');
  assert.equal(sandbox, 'allow-scripts allow-modals');
  assert.equal(await page.locator('.app-root').evaluate(el => el.inert), true);
  assert.equal(await frame.locator('body').evaluate(() => {try {return !!parent.document.body;} catch {return false;}}), false);
  checks.push('Opaque sandbox blocks parent DOM access in browser fixture');
  await page.evaluate(() => {window.dispatchEvent(new KeyboardEvent('keydown', {key:'x', bubbles:true})); window.dispatchEvent(new KeyboardEvent('keydown', {key:'ArrowRight', bubbles:true}));});
  await page.waitForFunction(() => window.__helpSurface?.title === 'Reading user guide');
  assert.ok(await page.evaluate(() => window.__helpSurface.keys.every(k => !k.enabled)));
  await page.evaluate(() => {window.__helpInput('key',0,1);window.__helpInput('dial',0,1);window.__helpInput('side',0,1);window.postMessage({scope:'photogogo-guide',type:'close'}, '*');});
  await delay(150);
  assert.ok(await dialog.isVisible());
  checks.push('Background inputs blocked; messages from other windows ignored');
  const pollsBefore = await page.evaluate(() => window.__helpCalls.filter(c => c.command==='process_jobs_snapshot').length);
  await delay(650);
  assert.ok(await page.evaluate(n => window.__helpCalls.filter(c => c.command==='process_jobs_snapshot').length>n,pollsBefore));
  checks.push('Core job monitor continues while guide is open');
  await frame.locator('#guide-search').fill('wind noise');
  const firstTarget = await frame.locator('#result-list a').first().getAttribute('href');
  await frame.locator('#guide-search').press('Enter');
  await frame.locator(firstTarget+'-title').evaluate(el => {if (document.activeElement!==el) throw Error('Search focus missing: active='+document.activeElement.id+'; hash='+location.hash);});
  await frame.locator('#guide-search').fill('');
  await frame.locator('#guide-search').press('Escape');
  await dialog.waitFor({state:'hidden'});
  assert.equal(await field.inputValue(), 'D:/Unsaved work');
  assert.ok(await button('Help for this page').evaluate(el=>document.activeElement===el));
  assert.equal(await page.locator('.app-root').evaluate(el=>el.inert),false);
  assert.equal(await page.evaluate(()=>window.__helpSavedSettings),undefined);
  checks.push('Escape inside frame closes Help, restores focus and retains unsaved field');
  await button('Help & User Guide').click();
  await dialog.waitFor();
  await frame.locator('#guide-search').waitFor();
  assert.equal(await frame.locator('.chapter').count(),18);
  await page.screenshot({path: output+'/embedded-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  const frameSize=await frame.locator('body').evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(()=>resolve({width:innerWidth,scroll:document.documentElement.scrollWidth,mobile:matchMedia('(max-width:900px)').matches})))));
  assert.ok(frameSize.mobile&&frameSize.width<=390&&frameSize.scroll<=frameSize.width,JSON.stringify(frameSize));
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path: output+'/embedded-mobile.png'});
  await button('Return to your work').click();
  checks.push('General entry, desktop/mobile dialog and explicit return work');
  assert.deepEqual(external,[]);
  assert.deepEqual(errors,[]);
  checks.push('No browser errors or external resource requests');
  await writeFile(output+'/report.json',JSON.stringify({passed:checks.length,checks,errors,external},null,2));
  console.log(JSON.stringify({passed:checks.length,checks}));
} catch(e) {await writeFile(output+'/failure.json',JSON.stringify({error:String(e.stack),checks,errors,external,logs},null,2)); console.error(e);process.exitCode=1;}
finally {await browser?.close();server.kill();}
